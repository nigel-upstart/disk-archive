"""Validate optional synthetic profile artifacts without printing artifact contents."""
from __future__ import annotations

import gzip
import json
import math
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

MAX_BYTES = 64 * 1024 * 1024
CANARIES = (
    b"SYNTHETIC-PRIVATE-TRACE-CANARY-7281",
    b"synthetic-profile-private-value",
    b"ghp_",
    b"-----BEGIN PRIVATE KEY-----",
)
STAGES = {"discovery", "scan", "redact", "prepare", "upload", "verify", "delete", "state", "manifest"}


def validate(mode: str, path: pathlib.Path) -> None:
    if not path.is_file() or path.is_symlink() or not 0 < path.stat().st_size <= MAX_BYTES:
        raise ValueError("profile artifact missing, unsafe or oversized")
    data = path.read_bytes()
    if data.startswith(b"\x1f\x8b"):
        with gzip.open(path, "rb") as stream:
            data = stream.read(MAX_BYTES + 1)
        if len(data) > MAX_BYTES:
            raise ValueError("decompressed profile exceeds bound")
    if any(marker in data for marker in CANARIES):
        raise ValueError("profile contains a planted private marker")
    if mode == "svg":
        # Artifacts are bounded and generated by the pinned local profiler, not untrusted XML.
        tree = ET.fromstring(data)
        if tree.tag != "{http://www.w3.org/2000/svg}svg":
            raise ValueError("invalid flamegraph SVG")
        decoded = ET.tostring(tree, encoding="utf-8")
        if any(marker in decoded for marker in CANARIES):
            raise ValueError("flamegraph contains an encoded planted private marker")
        titles = [node.text or "" for node in tree.iter("{http://www.w3.org/2000/svg}title")]
        if not any(re.search(r"\([1-9][0-9,]* samples?[,) ]", title) for title in titles):
            raise ValueError("flamegraph contains no sampled stack")
        return
    value = json.loads(data)
    if any(marker in json.dumps(value, ensure_ascii=False).encode() for marker in CANARIES):
        raise ValueError("profile contains an encoded planted private marker")
    if mode != "trace" and not isinstance(value, dict):
        raise ValueError("profile must be an object")
    if mode == "trace":
        if not isinstance(value, list) or not value:
            raise ValueError("empty or invalid Chrome trace")
        seen = set()
        for event in value:
            if not isinstance(event, dict):
                raise ValueError("invalid trace event")
            if event.get("ph") == "M":
                if (set(event) != {"ph", "pid", "name", "tid", "args"}
                        or event.get("name") != "thread_name" or type(event.get("tid")) is not int
                        or event.get("args") != {"name": "worker"}):
                    raise ValueError("unexpected trace thread metadata")
                continue
            stage = event.get("name")
            if stage not in STAGES or event.get("ph") not in ("B", "E"):
                raise ValueError("unexpected trace stage or phase")
            timestamp = event.get("ts")
            if type(timestamp) not in (int, float) or not math.isfinite(timestamp) or timestamp < 0:
                raise ValueError("invalid trace timestamp")
            if type(event.get("tid")) is not int:
                raise ValueError("invalid trace thread ordinal")
            args = event.get("args")
            if not isinstance(args, dict) or set(args) != {"file_id"}:
                raise ValueError("unexpected trace fields")
            if type(args["file_id"]) is not int or args["file_id"] < 0:
                raise ValueError("invalid opaque file ordinal")
            if set(event) - {"ph", "pid", "tid", "ts", "name", "cat", "args"}:
                raise ValueError("unexpected trace metadata")
            seen.add(stage)
        if not seen:
            raise ValueError("trace has no stage spans")
    elif mode == "heap":
        if value.get("dhatFileVersion") != 2 or value.get("mode") != "rust-heap":
            raise ValueError("invalid DHAT artifact")
        if value.get("cmd") != "disk-archive synthetic profile" or not value.get("pps"):
            raise ValueError("invalid heap metadata or empty allocation profile")
    elif mode == "console":
        if set(value) != {"schema", "tasks", "polls", "dropped_events"} or value["schema"] != 1:
            raise ValueError("invalid console receipt")
        if any(type(value[k]) is not int or value[k] < 0 for k in ("tasks", "polls", "dropped_events")):
            raise ValueError("invalid console counters")
        if not value["tasks"] or not value["polls"]:
            raise ValueError("console observed no polled tasks")
    elif mode == "run":
        if set(value) != {"schema", "files", "deleted", "retained", "rules", "verified_downloads", "process_spawns", "peak_temp_bytes"}:
            raise ValueError("invalid pipeline receipt")
        if any(type(v) is not int or v < 0 for v in value.values()):
            raise ValueError("invalid pipeline counters")
        if value["schema"] != 1 or value["files"] != 32 or value["deleted"] != 32 or value["verified_downloads"] != 32 or value["retained"] != 0 or value["rules"] != 488 or value["process_spawns"] != 0 or not value["peak_temp_bytes"]:
            raise ValueError("pipeline did not complete actual corpus verification")
    elif mode == "cpu":
        if not isinstance(value.get("meta"), dict) or not isinstance(value.get("threads"), list):
            raise ValueError("invalid samply Firefox profile")
        sampled = False
        for thread in value["threads"]:
            samples = thread.get("samples", {}) if isinstance(thread, dict) else {}
            if samples.get("length", 0) > 0 or samples.get("stack"):
                sampled = True
        if not sampled:
            raise ValueError("CPU profile has no samples")
    else:
        raise ValueError("unknown profile artifact type")


def main() -> None:
    if len(sys.argv) != 3:
        raise ValueError("usage: profile-validate.py MODE ARTIFACT")
    validate(sys.argv[1], pathlib.Path(sys.argv[2]))
    print("Synthetic profile format and planted-marker checks passed")


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, TypeError, AttributeError, ET.ParseError):
        # The messages above are static; never print JSON/parser details or values.
        print("Profile artifact validation failed", file=sys.stderr)
        sys.exit(1)
